"""
Шаблоны холодных цепочек Lemnity.

Каждая цепочка — список из 3 шагов. Поле offset_days — через сколько дней
ОТ ПЕРВОГО письма должен уйти этот шаг (0 / 3 / 7).

Подстановки в subject/body берутся из словаря контакта + конфига (.env):
  {recipient_name}  — контактное лицо (если пусто → подставляется нейтральное приветствие)
  {company}         — название студии/компании
  {website}         — сайт
  {city}            — город
  {commission}      — размер комиссии (из .env, по умолчанию «20–30%»)
  {demo_link}       — ссылка на демо-видео (из .env)
  {partner_link}    — ссылка на партнёрские условия (из .env)
  {sender_name}     — имя отправителя (из .env)
  {sender_email}    — почта отправителя (из .env)
  {sender_telegram} — телеграм/хэндл (из .env)

Тема для шагов 2 и 3 НЕ берётся отсюда — движок сам ставит "Re: " + тему
первого письма, чтобы письма склеились в один тред Gmail.
"""


class _SafeDict(dict):
    """str.format_map с этим словарём не падает на отсутствующих ключах."""
    def __missing__(self, key):
        return "{" + key + "}"


def render(text, fields):
    return text.format_map(_SafeDict(fields))


def greeting(fields):
    name = (fields.get("recipient_name") or "").strip()
    return f"Здравствуйте, {name}!" if name else "Здравствуйте!"


