SEQUENCES = {
    "studio": _STUDIO,
    "business": _BUSINESS,
}


def render_step(sequence_name, step_index, fields):
    """Вернёт (subject_or_None, body) для шага. subject не None только у шага 0."""
    steps = SEQUENCES[sequence_name]
    step = steps[step_index]
    f = dict(fields)
    f["greeting"] = greeting(f)
    subject = render(step["subject"], f) if step["subject"] else None
    body = render(step["body"], f)
    return subject, body


def offsets(sequence_name):
    return [s["offset_days"] for s in SEQUENCES[sequence_name]]
